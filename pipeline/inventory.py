"""Inventory every PSI table's columns and sample values (CLAUDE.md section 7).

Task D2. Writes data/raw/columns.md: one section per investigation with its
metadata and, for each experiment table, every column's exact name (quirks and
embedded units preserved) plus a few sample values to infer type and unit.
This is the reference for the D4 hand-mapping. Read-only over data/raw/.

Usage:
    python pipeline/inventory.py
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
TABLES = RAW / "tables"
OUT = RAW / "columns.md"

# Same order as fetch_psi.py, grouped by fire-safety area (CLAUDE.md section 3).
PSI_IDS = [
    "PSI-26", "PSI-25", "PSI-98", "PSI-99", "PSI-100", "PSI-20",
    "PSI-69", "PSI-68", "PSI-39",
    "PSI-102", "PSI-101", "PSI-47",
    "PSI-107", "PSI-106", "PSI-21", "PSI-10", "PSI-23", "PSI-22", "PSI-159",
    "PSI-62", "PSI-115", "PSI-117", "PSI-142", "PSI-60",
]
SAMPLE_ROWS = 60   # rows to scan for sample values
SAMPLE_VALS = 4    # distinct non-empty samples to show per column


def samples(rows: list[list[str]], col: int) -> str:
    """Up to SAMPLE_VALS distinct non-empty values for one column, as a string."""
    seen: list[str] = []
    for row in rows[:SAMPLE_ROWS]:
        if col < len(row):
            v = row[col].strip()
            if v and v not in seen:
                seen.append(v)
        if len(seen) >= SAMPLE_VALS:
            break
    return " · ".join(seen) if seen else "_(empty)_"


def table_section(path: Path) -> list[str]:
    with path.open(newline="", encoding="utf-8", errors="replace") as fh:
        rows = list(csv.reader(fh))
    if not rows:
        return [f"- `{path.name}` — **empty file**", ""]
    header, body = rows[0], rows[1:]
    out = [f"**Table:** `{path.name}` — {len(body)} rows × {len(header)} cols", ""]
    out.append("| # | column name | sample values |")
    out.append("|---|---|---|")
    for i, name in enumerate(header):
        shown = name if name.strip() else "_(blank header)_"
        # escape pipes so the markdown table stays intact
        shown = shown.replace("|", "\\|")
        vals = samples(body, i).replace("|", "\\|")
        out.append(f"| {i} | `{shown}` | {vals} |")
    out.append("")
    return out


def record_meta(psi_id: str) -> dict:
    data = json.loads((RAW / f"{psi_id}.json").read_text())
    return data


def main() -> int:
    lines = [
        "# PSI table inventory (D2)",
        "",
        "Auto-generated by `pipeline/inventory.py`. One section per investigation; "
        "column names are copied verbatim (NASA typos, trailing spaces and embedded "
        "units preserved). Reference for D4 hand-mapping — do not assume names, read "
        "them here.",
        "",
    ]
    n_tables = 0
    for psi_id in PSI_IDS:
        d = record_meta(psi_id)
        acronym = d.get("investigationAcronym") or ""
        title = d.get("title") or ""
        doi = d.get("doi") or ""
        hardware = d.get("experimentHardware") or ""
        platform = d.get("flightProgram") or ""
        area = d.get("researchArea") or ""
        n_pub = len(d.get("publications") or [])
        entries = d.get("experimentalTable") or []

        lines.append(f"## {psi_id} — {acronym} ({title})")
        lines.append("")
        lines.append(
            f"- DOI: `{doi}` · hardware: {hardware or '—'} · platform: {platform or '—'}"
        )
        lines.append(
            f"- research area: {area or '—'} · publications: {n_pub} · "
            f"tables referenced: {len(entries)}"
        )
        lines.append("")
        if not entries:
            lines.append("_No experiment table (text-only / modelling investigation)._")
            lines.append("")
            continue
        for entry in entries:
            fname = entry.get("file_name", "")
            path = TABLES / fname
            if not path.exists():
                lines.append(f"- `{fname}` — **file missing in data/raw/tables/**")
                lines.append("")
                continue
            lines.extend(table_section(path))
            n_tables += 1

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(PSI_IDS)} investigations, {n_tables} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
